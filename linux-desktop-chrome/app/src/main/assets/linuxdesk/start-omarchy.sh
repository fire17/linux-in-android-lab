#!/bin/sh
# LinuxDesk "Omarchy": start the i3 desktop with Omarchy's look, then Chrome as its first window.
# Runs INSIDE the Arch Linux ARM guest under PRoot. Same argv contract as start-browser.sh, so the app and deskd
# (LINUXDESK_BROWSER_CMD) can use either one: all arguments are browser flags plus the URL (ChromiumFlags.kt).
#
# Differences from start-browser.sh (Alpine):
#   - i3 manages the windows, so fit-window.sh is NOT run. i3 tiles Chrome to the whole screen (minus the bar)
#     and follows RandR resizes when the phone rotates. A small watcher still prints LINUXDESK_WINDOW_UP once,
#     which the app waits for to show RUNNING.
#   - The browser is google-chrome-stable (Omarchy's default), or chromium if Chrome is not installed.
#   - --window-position/--window-size/--start-maximized are dropped: i3 sizes the window.
# This script exits with the browser's code, which is what the app's "browser exited" state and deskd expect;
# proot's --kill-on-exit then ends i3 and anything started from it. "Restart browser" starts both again.
# (Keeping i3 up after the browser closes is OPEN: it needs a session-level parent other than the browser.)
export DISPLAY="${DISPLAY:-:0}"
export XDG_RUNTIME_DIR=/tmp/runtime-root
export LANG="${LANG:-C.UTF-8}"
export HOME="${HOME:-/root}"
mkdir -p "$XDG_RUNTIME_DIR" && chmod 700 "$XDG_RUNTIME_DIR"

i=0
while [ ! -e /tmp/.X11-unix/X0 ] && [ $i -lt 40 ]; do sleep 0.5; i=$((i + 1)); done
[ -e /tmp/.X11-unix/X0 ] || echo "[omarchy] warning: /tmp/.X11-unix/X0 not found, trying anyway"

BIN=""
for b in google-chrome-stable chromium; do command -v "$b" >/dev/null 2>&1 && { BIN=$b; break; }; done
if [ -z "$BIN" ]; then
  echo "[omarchy] no browser installed (setup-omarchy.sh did not finish?)"
  exit 127
fi

# The app copies its helper dir without exec bits; i3 bindings and rofi entries run these scripts.
chmod +x /opt/linuxdesk/omarchy/*.sh 2>/dev/null || true
# bubblewrap cannot sandbox under PRoot, so glycin failed every image (no wallpaper; wofi crashed on Super+Space).
# The shim runs glycin's loaders unsandboxed; /usr/local/bin is ahead of /usr/bin on PATH (2026-11-20, 0.2.29).
cmp -s /opt/linuxdesk/omarchy/bwrap-shim.sh /usr/local/bin/bwrap 2>/dev/null \
  || install -m 755 /opt/linuxdesk/omarchy/bwrap-shim.sh /usr/local/bin/bwrap 2>/dev/null || true

# One UI scale S for the whole desktop = Chrome's --force-device-scale-factor (ChromiumFlags.kt: Android density x the
# app's scale %), taken from our own argv: deskd's launch strips LINUXDESK_* from the environment, the flags arrive on
# both paths. X runs at the phone's densityDpi (~420), so i3 sized its 10pt bar font from that (~59 px) while rofi
# used 96 dpi (tiny). Xft.dpi = 96*S on the root window makes every Xft/pango client agree with Chrome; the
# theme renderer sizes i3, polybar, rofi, dunst and alacritty from S as well.
S=1
for a in "$@"; do
  case "$a" in --force-device-scale-factor=*) S=${a#--force-device-scale-factor=} ;; esac
done
case "$S" in ''|*[!0-9.]*) S=1 ;; esac
export LINUXDESK_UI_SCALE="$S"
mkdir -p /etc/linuxdesk && echo "$S" > /etc/linuxdesk/ui-scale   # the theme menu re-renders without this env
DPI=$(awk -v s="$S" 'BEGIN { printf "%d", 96 * s + 0.5 }')
# xrdb is not installed; RESOURCE_MANAGER is the property xrdb would write. Xcursor.size keeps the pointer in scale.
xprop -root -format RESOURCE_MANAGER 8s -set RESOURCE_MANAGER \
  "$(printf 'Xft.dpi:\t%s\nXcursor.size:\t%s\n' "$DPI" "$(awk -v s="$S" 'BEGIN { printf "%d", 24 * s + 0.5 }')")" 2>/dev/null \
  || echo "[omarchy] note: could not set Xft.dpi (xprop failed)"
# alacritty (winit) takes its scale from Xft.dpi too; pinning it avoids a winit that reads the X screen instead.
export WINIT_X11_SCALE_FACTOR="$S"
echo "[omarchy] UI scale $S (Xft.dpi $DPI)"

# The theme renders once at setup; re-render if the config is missing (e.g. HOME was wiped), was generated by an
# older omarchy-theme.py (see I3_REV there) or for another UI scale (the app's scale % changed), keeping the theme.
if ! grep -qxF "$(python3 /opt/linuxdesk/omarchy/omarchy-theme.py --stamp 2>/dev/null || echo '#none')" "$HOME/.config/i3/config" 2>/dev/null; then
  python3 /opt/linuxdesk/omarchy/omarchy-theme.py "$(cat /etc/linuxdesk/omarchy-theme 2>/dev/null || echo tokyo-night)"
fi

# The look stage (setup-omarchy.sh look, optional): polybar + picom, ~2 MB. Until it is done the desktop runs with
# i3bar and no compositor (bar.sh and compositor.sh fall back by themselves); when it finishes, i3 reloads.
LOOK=0
if [ "$(cat /etc/linuxdesk/look-v1 2>/dev/null)" != 1 ] && [ -f /opt/linuxdesk/setup-omarchy.sh ]; then
  LOOK=1; echo "[omarchy] installing polybar + picom in the background (log: /etc/linuxdesk/omarchy-look.log)"
fi
# Omarchy's apps (setup-omarchy.sh stage 8, optional): installed in the background while the desktop is already up,
# for new and for already-installed rootfs (the first-run setup skips stages by their markers and never sees stage 8).
# Its "apps:" lines go to the session log; pacman's full output to /etc/linuxdesk/omarchy-apps.log. setup-omarchy.sh
# holds a lock, so a second Start (or "Restart browser") does not start a second install. Never blocks the browser.
APPS=0
if [ "$(cat /etc/linuxdesk/omarchy-stage-8 2>/dev/null)" != 1 ] && [ -f /opt/linuxdesk/setup-omarchy.sh ]; then
  APPS=1; echo "[omarchy] installing Omarchy's apps in the background (log: /etc/linuxdesk/omarchy-apps.log)"
fi
# One background job, look first (small), then apps: two pacman runs at once would fight over pacman's lock.
if [ "$LOOK" = 1 ] || [ "$APPS" = 1 ]; then
  (
    if [ "$LOOK" = 1 ]; then
      nice -n 10 sh /opt/linuxdesk/setup-omarchy.sh look 2>&1 | tee -a /etc/linuxdesk/omarchy-look.log \
        | grep --line-buffered '^\[omarchy\] look:'
      [ "$(cat /etc/linuxdesk/look-v1 2>/dev/null)" = 1 ] && i3-msg -q reload 2>/dev/null
    fi
    if [ "$APPS" = 1 ]; then
      nice -n 10 sh /opt/linuxdesk/setup-omarchy.sh apps 2>&1 | tee -a /etc/linuxdesk/omarchy-apps.log \
        | grep --line-buffered '^\[omarchy\] apps:'
    fi
  ) &
fi

# Drop flags that fight a window manager. GPU guard: without GPU mode's --use-gl= (ChromiumFlags.GPU_FLAGS) the
# browser always gets --disable-gpu, whatever Mesa the guest has (setup-gpu.sh's kgsl Mesa must never be tried
# with GPU mode OFF). SwiftShader stays available: no --disable-software-rasterizer.
n=$#; GL=0
while [ "$n" -gt 0 ]; do
  a=$1; shift; n=$((n - 1))
  case "$a" in
    --window-position=*|--window-size=*|--start-maximized) ;;
    --use-gl=*|--disable-gpu) GL=1; set -- "$@" "$a" ;;
    *) set -- "$@" "$a" ;;
  esac
done
[ "$GL" = 1 ] || { set -- --disable-gpu "$@"; echo "[omarchy] GPU mode off: added --disable-gpu"; }

I3=""
if command -v i3 >/dev/null 2>&1 && ! xprop -root _NET_SUPPORTING_WM_CHECK 2>/dev/null | grep -q 'window id'; then
  i3 >/tmp/i3.log 2>&1 &
  I3=$!
  # Wait (max ~5 s) for i3 to own the screen, so Chrome is mapped as a managed (tiled) window.
  i=0
  while [ $i -lt 20 ] && ! xprop -root _NET_SUPPORTING_WM_CHECK 2>/dev/null | grep -q 'window id'; do
    sleep 0.25; i=$((i + 1))
  done
  echo "[omarchy] i3 started (pid $I3)"
else
  echo "[omarchy] i3 already running or not installed; starting the browser alone"
fi

# LINUXDESK_WINDOW_UP: the app shows RUNNING when the first browser window is viewable.
(
  j=0
  while [ $j -lt 240 ]; do
    if xdotool search --onlyvisible --class 'chrom' >/dev/null 2>&1; then
      echo "LINUXDESK_WINDOW_UP $(xdotool getdisplaygeometry 2>/dev/null | tr ' ' x)"
      exit 0
    fi
    sleep 0.5; j=$((j + 1))
  done
) &
WATCH=$!

echo "[omarchy] exec $BIN $*"
"$BIN" "$@"
CODE=$?
kill "$WATCH" 2>/dev/null
echo "[omarchy] $BIN exited with code $CODE"
exit $CODE
